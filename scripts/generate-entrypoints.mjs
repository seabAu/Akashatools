import { mkdir, readdir, readFile, unlink, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const checkOnly = process.argv.includes("--check");
const categories = [
  "array",
  "async",
  "browser",
  "collection",
  "data",
  "date",
  "http",
  "hash",
  "geo",
  "input",
  "function",
  "number",
  "object",
  "random",
  "sort",
  "string",
  "validation",
  "node",
];
let methodCount = 0;
const failures = [];

for (const category of categories) {
  const source = await readFile(new URL(`src/${category}.js`, root), "utf8");
  const names = [...source.matchAll(/^export\s+(?:async\s+)?(?:class|function|const)\s+([A-Za-z_$][\w$]*)/gm)].map(
    ([, name]) => name,
  );
  if (new Set(names).size !== names.length) throw new Error(`${category} contains duplicate public declaration names.`);
  methodCount += names.length;

  const expected = new Map([
    ["index.js", `// Generated by scripts/generate-entrypoints.mjs.\nexport * from "../${category}.js";\n`],
    ...names.map((name) => [
      `${name}.js`,
      `// Generated by scripts/generate-entrypoints.mjs.\nexport { ${name}, ${name} as default } from "../${category}.js";\n`,
    ]),
  ]);
  const directory = new URL(`src/${category}/`, root);
  await mkdir(directory, { recursive: true });
  const existing = (await readdir(directory)).filter((name) => name.endsWith(".js"));

  if (checkOnly) {
    for (const filename of existing) {
      if (!expected.has(filename)) failures.push(`unexpected generated entrypoint: src/${category}/${filename}`);
    }
    for (const [filename, content] of expected) {
      const actual = await readFile(new URL(filename, directory), "utf8").catch(() => "");
      if (actual !== content) failures.push(`stale generated entrypoint: src/${category}/${filename}`);
    }
    continue;
  }

  for (const filename of existing) {
    if (!expected.has(filename)) await unlink(new URL(filename, directory));
  }
  await Promise.all([...expected].map(([filename, content]) => writeFile(new URL(filename, directory), content)));
}

if (failures.length > 0) {
  console.error(`Generated entrypoint check failed for ${failures.length} file(s):`);
  for (const failure of failures) console.error(`- ${failure}`);
  process.exitCode = 1;
} else if (checkOnly) {
  console.log(`Generated category and ${methodCount} granular entrypoints are current.`);
} else {
  console.log(`Generated ${categories.length} category indexes and ${methodCount} granular method entrypoints.`);
}
